/*
 * 冷却控制板内部 Flash 的唯一分区定义。
 *
 * STM32F302CCT6 共 256 KiB Flash，最小擦除粒度为 2 KiB。
 * Bootloader、App、RBL 下载区和参数区均严格按 2 KiB 页对齐。
 */

#ifndef COOLING_FLASH_LAYOUT_H
#define COOLING_FLASH_LAYOUT_H

#include <stdint.h>

#define COOLING_FLASH_BASE_ADDRESS       UINT32_C(0x08000000)
#define COOLING_FLASH_TOTAL_SIZE         (UINT32_C(256) * UINT32_C(1024))
#define COOLING_FLASH_PAGE_SIZE          UINT32_C(0x800)

#define COOLING_BL_OFFSET                UINT32_C(0x00000)
#define COOLING_BL_SIZE                  UINT32_C(0x08000) /* 32 KiB */

/* Bootloader 最后一个独立擦除页的页首由下载器写入 UID 密钥。 */
#define COOLING_UID_KEY_PAGE_OFFSET      UINT32_C(0x07800)
#define COOLING_UID_KEY_PAGE_SIZE        UINT32_C(0x00800)
#define COOLING_UID_KEY_OFFSET           COOLING_UID_KEY_PAGE_OFFSET
#define COOLING_UID_KEY_SIZE             UINT32_C(12)

#define COOLING_APP_OFFSET               UINT32_C(0x08000)
#define COOLING_APP_SIZE                 UINT32_C(0x1A800) /* 106 KiB */

#define COOLING_DOWNLOAD_OFFSET          UINT32_C(0x22800)
#define COOLING_DOWNLOAD_SIZE            UINT32_C(0x1A800) /* 106 KiB */

#define COOLING_OTA_META_OFFSET          UINT32_C(0x3D000)
#define COOLING_OTA_META_SIZE            UINT32_C(0x01000) /* 4 KiB，两个状态页 */

#define COOLING_NV_PARAM_OFFSET          UINT32_C(0x3E000)
#define COOLING_NV_PARAM_SIZE            UINT32_C(0x02000) /* 8 KiB */

#define COOLING_BL_START_ADDRESS         (COOLING_FLASH_BASE_ADDRESS + COOLING_BL_OFFSET)
#define COOLING_UID_KEY_START_ADDRESS    (COOLING_FLASH_BASE_ADDRESS + COOLING_UID_KEY_OFFSET)
#define COOLING_APP_START_ADDRESS        (COOLING_FLASH_BASE_ADDRESS + COOLING_APP_OFFSET)
#define COOLING_DOWNLOAD_START_ADDRESS   (COOLING_FLASH_BASE_ADDRESS + COOLING_DOWNLOAD_OFFSET)
#define COOLING_OTA_META_START_ADDRESS   (COOLING_FLASH_BASE_ADDRESS + COOLING_OTA_META_OFFSET)
#define COOLING_NV_PARAM_START_ADDRESS   (COOLING_FLASH_BASE_ADDRESS + COOLING_NV_PARAM_OFFSET)
#define COOLING_FLASH_END_ADDRESS        (COOLING_FLASH_BASE_ADDRESS + COOLING_FLASH_TOTAL_SIZE)

#define COOLING_FAL_FLASH_NAME           "onchip_flash"
#define COOLING_FAL_BL_PART_NAME         "bl"
#define COOLING_FAL_APP_PART_NAME        "app"
#define COOLING_FAL_DOWNLOAD_PART_NAME   "download"
#define COOLING_FAL_OTA_META_PART_NAME   "ota_meta"
#define COOLING_FAL_NV_PARAM_PART_NAME   "nv_param"

/* 编译期检查：任何一项不对齐或总长度错误都禁止生成固件。 */
#if ((COOLING_BL_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_BL_SIZE % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_APP_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_APP_SIZE % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_DOWNLOAD_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_DOWNLOAD_SIZE % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_OTA_META_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_OTA_META_SIZE % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_NV_PARAM_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_NV_PARAM_SIZE % COOLING_FLASH_PAGE_SIZE) != 0)
#error "CoolingCtrlBoard Flash partition is not page aligned"
#endif

#if ((COOLING_UID_KEY_PAGE_OFFSET % COOLING_FLASH_PAGE_SIZE) != 0) || \
    ((COOLING_UID_KEY_PAGE_OFFSET + COOLING_UID_KEY_PAGE_SIZE) != COOLING_BL_SIZE) || \
    ((COOLING_UID_KEY_OFFSET + COOLING_UID_KEY_SIZE) > COOLING_BL_SIZE)
#error "CoolingCtrlBoard UID key slot is outside the Bootloader partition"
#endif

#if ((COOLING_NV_PARAM_OFFSET + COOLING_NV_PARAM_SIZE) != COOLING_FLASH_TOTAL_SIZE)
#error "CoolingCtrlBoard Flash partition size mismatch"
#endif

#endif /* COOLING_FLASH_LAYOUT_H */
